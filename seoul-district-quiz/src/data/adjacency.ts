const EMPTY_NEIGHBORS = Object.freeze([]) as readonly string[]

function buildAdjacency(edges: readonly AdjacencyEdge[]): Readonly<Record<string, readonly string[]>> {
  const neighborsById = new Map<string, Set<string>>()

  for (const [regionId, neighborId] of edges) {
    const regionNeighbors = neighborsById.get(regionId) ?? new Set<string>()
    const neighborNeighbors = neighborsById.get(neighborId) ?? new Set<string>()

    regionNeighbors.add(neighborId)
    neighborNeighbors.add(regionId)
    neighborsById.set(regionId, regionNeighbors)
    neighborsById.set(neighborId, neighborNeighbors)
  }

  return Object.freeze(
    Object.fromEntries(
      [...neighborsById].map(([regionId, neighborIds]) => [
        regionId,
        Object.freeze([...neighborIds].toSorted()),
      ]),
    ),
  )
}

export const ADJACENCY_BY_REGION_ID = buildAdjacency([
  ...SEOUL_EDGES,
  ...GYEONGGI_EDGES,
  ...CROSS_PACK_EDGES,
  ...DETAIL_EDGES,
])

export function getNeighbors(regionId: string): readonly string[] {
  return ADJACENCY_BY_REGION_ID[regionId] ?? EMPTY_NEIGHBORS
}
